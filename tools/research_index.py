"""Generate docs/research_index.md, a reader's map of the hash-locked research snapshot.

The index is built from research/snapshot_manifest.json alone. It never imports or runs a research module.
Run without arguments to rewrite the index, or with --check to fail when the committed index is stale.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "research" / "snapshot_manifest.json"
INDEX = ROOT / "docs" / "research_index.md"

# Short codes and names of the retained analyses, in the order of docs/research_reproduction.md.
ANALYSES = {
    "run_bran_robust_clinical_r7.py": ("R7", "R7 retained training"),
    "run_bran_robust_clinical_evaluation_r7.py": ("R7E", "R7 native and historical evaluation"),
    "run_bran_r7_modality_atlas_a3.py": ("A3", "A3 modality atlas"),
    "run_bran_r7_information_matched_f1.py": ("F1", "F1 information-matched comparison"),
    "run_bran_mimic_broad_state_m2.py": ("M2", "M2 MIMIC state"),
    "bran_r7_missingness_figure_m2.py": ("M2F", "M2 missingness figure renderer"),
    "run_bran_r7_completion_utility_u2.py": ("U2", "U2 completion utility"),
    "run_bran_r7_quantile_q4.py": ("Q4", "Q4 quantile analysis"),
    "run_bran_r7_clinical_s4.py": ("S4", "S4 clinical panel"),
    "run_bran_expanded_clinical_s7.py": ("S7", "S7 expanded clinical panel"),
    "run_bran_r7_inspire_e1.py": ("E1", "INSPIRE E1"),
    "run_bran_hirid_r7_h6.py": ("H6", "HiRID H6"),
}
VERSION_TOKEN = re.compile(r"_(v\d+(?:_\d+)*|attempt\d+|[a-z]\d{1,2})$")
RENDERER = "M2F"   # renders an approved aggregate and imports nothing local, so it is not a runner
LEGACY_PREFIXES = ("patient_atlas", "soft_patient_atlas", "bran_multisource", "bran_agefree")


def family(module: str) -> str:
    """Module name without trailing version, attempt and stage tokens such as _v6_2, _attempt2 or _h6."""
    stem = module[:-3] if module.endswith(".py") else module
    while True:
        shorter = VERSION_TOKEN.sub("", stem)
        if shorter == stem:
            return stem
        stem = shorter


def build(manifest: dict) -> str:
    modules = manifest["modules"]
    reach = manifest["entrypoint_dependencies"]
    assert set(reach) == set(ANALYSES), "entrypoints changed, update ANALYSES"
    roles: dict[str, dict[str, str]] = defaultdict(dict)
    for entry, reached in reach.items():
        direct = set(modules[entry]["local_imports"])
        for name in reached:
            code = ANALYSES[entry][0]
            roles[name][code] = "entrypoint" if name == entry else "direct" if name in direct else "transitive"
    families: dict[str, list[str]] = defaultdict(list)
    for name in modules:
        families[family(name)].append(name)
    multi = {key: sorted(names) for key, names in families.items() if len(names) > 1}
    runners = {code for code, _ in ANALYSES.values()} - {RENDERER}
    shared_by_all = sum(1 for name in modules if runners <= set(roles[name]))
    legacy = {prefix: sum(1 for name in modules if name.startswith(prefix)) for prefix in LEGACY_PREFIXES}
    order = [code for code, _ in ANALYSES.values()]

    out = [
        "# Research snapshot index",
        "",
        "This file is generated by `python tools/research_index.py` from `research/snapshot_manifest.json`. "
        "Do not edit it by hand. `python tools/research_index.py --check` fails when it is stale.",
        "",
        f"The snapshot holds {len(modules)} modules in {len(families)} name families. "
        f"{len(multi)} families have more than one version, and {shared_by_all} modules are reached by all "
        f"{len(runners)} retained runners. A version suffix does not mean dead code. Every module listed here is reached by at "
        "least one retained analysis through static imports.",
        "",
        "Module names keep the working names of earlier project stages. "
        + ", ".join(f"`{p}` ({n} modules)" for p, n in legacy.items())
        + " are such names. They identify code that the retained R7 runners still import, and they are kept "
        "because the snapshot must stay byte-identical to the code that produced the results.",
        "",
        "## Analyses",
        "",
        "| Code | Analysis | Entrypoint | Modules reached |",
        "| --- | --- | --- | --- |",
    ]
    for entry, (code, title) in ANALYSES.items():
        out.append(f"| {code} | {title} | `{entry}` | {len(reach[entry])} |")
    out += [
        "",
        "## Families with more than one version",
        "",
        "| Family | Versions |",
        "| --- | --- |",
    ]
    for key in sorted(multi):
        out.append(f"| `{key}` | " + ", ".join(f"`{n}`" for n in multi[key]) + " |")
    out += [
        "",
        "## Modules",
        "",
        "Role is entrypoint, direct (imported by the entrypoint) or transitive. A module reached by all "
        f"{len(runners)} runners is marked all runners, with M2F added when the renderer reaches it too.",
        "",
        "| Module | Reached by | Role | Other versions |",
        "| --- | --- | --- | --- |",
    ]
    for name in sorted(modules):
        codes = [code for code in order if code in roles[name]]
        kinds = sorted(set(roles[name].values()), key=["entrypoint", "direct", "transitive"].index)
        if runners <= set(codes):
            reached = "all runners" + (", M2F" if RENDERER in codes else "")
        else:
            reached = ", ".join(codes)
        others = [n for n in families[family(name)] if n != name]
        out.append(f"| `{name}` | {reached} | {', '.join(kinds)} | "
                   + (", ".join(f"`{n}`" for n in sorted(others)) or "none") + " |")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/research_index.md is stale")
    args = parser.parse_args()
    text = build(json.loads(MANIFEST.read_text(encoding="utf-8")))
    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.is_file() else ""
        if current != text:
            print("docs/research_index.md is stale, run python tools/research_index.py", file=sys.stderr)
            return 1
        print("docs/research_index.md is current")
        return 0
    INDEX.write_text(text, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
